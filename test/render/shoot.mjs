// Open the Studio test page, import the warrior, and take screenshots of each mode.
import { mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import { serve } from './server.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const OUT = process.env.OUT ?? new URL('./out/', import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });
await build({ entryPoints: [new URL('./studio-harness.ts', import.meta.url).pathname], bundle: true, format: 'iife', outfile: new URL('./out/studio-harness.js', import.meta.url).pathname, target: 'es2022', logLevel: 'error' });
const { server, url } = await serve();
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 860 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto(`${url}/test/render/studio.html`);
await page.waitForFunction(() => window.harnessReady === true);
await page.screenshot({ path: OUT + 'studio_empty.png' });
await page.evaluate(() => window.studio.importImage());
await page.waitForTimeout(400);
await page.screenshot({ path: OUT + 'studio_rig.png' });
await page.evaluate(() => window.studio.select('arm_upper_front'));
await page.evaluate(() => window.studio.setMode('paint'));
await page.waitForTimeout(200);
await page.screenshot({ path: OUT + 'studio_paint.png' });
await page.evaluate(() => window.studio.setMode('animate'));
await page.waitForTimeout(450);
await page.screenshot({ path: OUT + 'studio_animate.png' });
await page.evaluate(() => window.setNextImage('../sprites/swordsman_white.png'));
await page.evaluate(() => window.studio.importImage());
await page.waitForTimeout(500);
await page.evaluate(() => window.studio.setMode('rig'));
await page.waitForTimeout(200);
await page.screenshot({ path: OUT + 'studio_autorig.png' });
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors');
await browser.close();
server.close();
